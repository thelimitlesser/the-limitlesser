let currentLang = localStorage.getItem('lang');

async function detectLanguage() {
  if (currentLang) return currentLang;
  
  try {
    const response = await fetch('/api/geo');
    const data = await response.json();
    if (data.country && data.country === 'HU') {
      return 'hu';
    }
  } catch (error) {
    console.warn('Language detection failed, defaulting to EN', error);
  }
  return 'en';
}

function updateContent(lang) {
  currentLang = lang;
  localStorage.setItem('lang', lang);
  document.documentElement.lang = lang;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang][key]) {
      el.innerHTML = translations[lang][key];
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (translations[lang][key]) {
      el.placeholder = translations[lang][key];
    }
  });

  // Update Dropdown UI if it exists
  const flagMap = {
    hu: 'https://flagcdn.com/w80/hu.png',
    en: 'https://flagcdn.com/w80/gb.png'
  };

  document.querySelectorAll('.currentFlag').forEach(img => {
    img.src = flagMap[lang];
  });

  document.querySelectorAll('.lang-option').forEach(opt => {
    opt.classList.toggle('active', opt.dataset.langOpt === lang);
  });

  // Special handling for floating words if they exist in the DOM
  const lwElements = document.querySelectorAll('.lw');
  if (lwElements.length > 0) {
    lwElements.forEach((el, index) => {
      const key = `word_${(index % 6) + 1}`;
      if (translations[lang][key]) {
        el.innerHTML = translations[lang][key];
      }
    });
  }

  // ─── Dynamic SEO Meta Updates ───────────────────────────────
  const seoMeta = {
    hu: {
      title: 'Limitlesser — Digitális Transzformáció KKV-knak',
      desc: 'A Limitlesser segít KKV-knak digitálisan fejlődni: egyedi szoftver, AI eszközök és digitális stratégia — mérhető eredményekkel.',
      descShort: 'A Limitlesser segít KKV-knak digitálisan fejlődni: egyedi szoftver, AI eszközök és digitális stratégia.',
      url: 'https://limitlesser.com/',
      locale: 'hu_HU',
      canonical: 'https://limitlesser.com/'
    },
    en: {
      title: 'Limitlesser — Digital Transformation for SMBs',
      desc: 'Limitlesser helps SMBs grow digitally: custom software, AI tools and digital strategy — with measurable results.',
      descShort: 'Limitlesser helps SMBs grow digitally: custom software, AI tools and digital strategy.',
      url: 'https://limitlesser.com/en/',
      locale: 'en_US',
      canonical: 'https://limitlesser.com/en/'
    }
  };
  const m = seoMeta[lang] || seoMeta.hu;

  // Title
  document.title = m.title;
  const ptEl = document.getElementById('page-title');
  if (ptEl) ptEl.textContent = m.title;

  // Meta description
  const pdEl = document.getElementById('page-desc');
  if (pdEl) pdEl.setAttribute('content', m.desc);

  // Canonical
  const canonEl = document.getElementById('canonical-tag');
  if (canonEl) canonEl.setAttribute('href', m.canonical);

  // Open Graph
  const ogTitleEl = document.getElementById('og-title');
  if (ogTitleEl) ogTitleEl.setAttribute('content', m.title);
  const ogDescEl = document.getElementById('og-desc');
  if (ogDescEl) ogDescEl.setAttribute('content', m.desc);
  const ogUrlEl = document.getElementById('og-url');
  if (ogUrlEl) ogUrlEl.setAttribute('content', m.url);
  const ogLocaleEl = document.getElementById('og-locale');
  if (ogLocaleEl) ogLocaleEl.setAttribute('content', m.locale);

  // Twitter Card
  const twTitleEl = document.getElementById('tw-title');
  if (twTitleEl) twTitleEl.setAttribute('content', m.title);
  const twDescEl = document.getElementById('tw-desc');
  if (twDescEl) twDescEl.setAttribute('content', m.descShort);
}

// Prevent FOUC
document.documentElement.classList.add('unresolved');

async function initI18n() {
  const lang = await detectLanguage();
  console.log('Limitlesser i18n Initializing...', lang);
  updateContent(lang);
  // Re-run update after a short delay to ensure DOM is fully ready and CSS is applied
  setTimeout(() => updateContent(lang), 100);
  document.documentElement.classList.remove('unresolved');
  document.dispatchEvent(new Event('i18nReady'));
}

// Global toggle functions for dropdown
window.toggleLangDropdown = (e) => {
  if (e) {
    const dd = e.currentTarget.closest('.lang-dropdown');
    if (dd) dd.classList.toggle('open');
    e.stopPropagation();
  }
};

window.selectLanguage = (lang) => {
  updateContent(lang);
  document.querySelectorAll('.lang-dropdown').forEach(dd => dd.classList.remove('open'));
};

// Close dropdown when clicking outside
document.addEventListener('click', (e) => {
  document.querySelectorAll('.lang-dropdown').forEach(dd => {
    if (!dd.contains(e.target)) {
      dd.classList.remove('open');
    }
  });
});

window.setLanguage = (lang) => {
  updateContent(lang);
};

document.addEventListener('DOMContentLoaded', initI18n);
