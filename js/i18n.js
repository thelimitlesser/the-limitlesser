let currentLang = localStorage.getItem('limitlesser_lang');

async function detectLanguage() {
  if (currentLang) return currentLang;
  
  try {
    const response = await fetch('https://ipapi.co/json/');
    const data = await response.json();
    if (data.country_code === 'HU') {
      return 'hu';
    }
  } catch (error) {
    console.warn('Language detection failed, defaulting to EN', error);
  }
  return 'en';
}

function updateContent(lang) {
  currentLang = lang;
  localStorage.setItem('limitlesser_lang', lang);
  document.documentElement.lang = lang;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang][key]) {
      el.innerHTML = translations[lang][key];
    }
  });

  // Update Dropdown UI if it exists
  const currentFlag = document.getElementById('currentFlag');
  if (currentFlag) {
    const flagMap = {
      hu: 'https://flagcdn.com/w80/hu.png',
      en: 'https://flagcdn.com/w80/gb.png'
    };
    currentFlag.src = flagMap[lang];
    
    document.querySelectorAll('.lang-option').forEach(opt => {
      opt.classList.toggle('active', opt.dataset.langOpt === lang);
    });
  }

  // Special handling for floating words if they exist in the DOM
  const lwElements = document.querySelectorAll('.lw');
  if (lwElements.length > 0) {
    lwElements.forEach((el, index) => {
      const key = `word_${(index % 6) + 1}`;
      el.textContent = translations[lang][key];
    });
  }
}

async function initI18n() {
  const lang = await detectLanguage();
  updateContent(lang);
}

// Global toggle functions for dropdown
window.toggleLangDropdown = () => {
  const dd = document.getElementById('langDropdown');
  if (dd) dd.classList.toggle('open');
};

window.selectLanguage = (lang) => {
  updateContent(lang);
  const dd = document.getElementById('langDropdown');
  if (dd) dd.classList.remove('open');
};

// Close dropdown when clicking outside
document.addEventListener('click', (e) => {
  const dd = document.getElementById('langDropdown');
  if (dd && !dd.contains(e.target)) {
    dd.classList.remove('open');
  }
});

window.setLanguage = (lang) => {
  updateContent(lang);
};

document.addEventListener('DOMContentLoaded', initI18n);
